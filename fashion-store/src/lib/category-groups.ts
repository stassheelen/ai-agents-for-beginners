/** Words of a text in lower case, apostrophes dropped. */
const words = (text: string) =>
  text
    .toLowerCase()
    .replace(/['’ʼ`]/g, "")
    .split(/[^a-zа-щьюяґєії0-9]+/i)
    .filter(Boolean);

function match(text: string): { group: CategoryGroup; type: string } | null {
  const ws = words(text);
  for (const [group, type, stems] of RULES) {
    // Short stems ("топ", "кед", "мом") must be the whole word to avoid hits inside other words.
    if (stems.some((s) => ws.some((w) => (s.length <= 3 ? w === s || w === `${s}и` || w === `${s}а` : w.startsWith(s))))) return { group, type };
  }
  return null;
}

/** Group + product type for a product, from its name and (as a fallback) the supplier's category names. */
export function classifyProduct(name: string, supplierCategories: (string | null | undefined)[] = []): { group: CategoryGroup; type: string | null } {
  const firstWord = words(name)[0] ?? "";
  const hit = match(firstWord) ?? match(name) ?? match(supplierCategories.filter(Boolean).join(" "));
  return hit ?? { group: "Інше", type: null };
}
