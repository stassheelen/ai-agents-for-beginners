/** Letters that only appear in Russian. */
const RUSSIAN_ONLY = /[ыэёъ]/i;

function convertWord(word: string) {
  const lower = word.toLowerCase();
  let out = WORDS[lower];
  // Fallback for adjectives that are not in the list: -ый → -ий, ы → и, э → е.
  if (!out && RUSSIAN_ONLY.test(lower)) out = lower.replace(/ый$/, "ий").replace(/ы/g, "и").replace(/э/g, "е").replace(/ё/g, "ьо").replace(/ъ/g, "'");
  if (!out) return word;
  if (word === word.toUpperCase() && word.length > 1) return out.toUpperCase();
  return word[0] === word[0].toUpperCase() ? out[0].toUpperCase() + out.slice(1) : out;
}

/** Ukrainian version of a short label; unchanged when nothing in it looks Russian. */
export function ukLabel<T extends string | null | undefined>(text: T): T {
  if (!text) return text;
  const words = text.match(/[a-zа-яёіїєґ'’]+/gi) ?? [];
  const looksRussian = RUSSIAN_ONLY.test(text) || words.some((w) => w.length > 1 && WORDS[w.toLowerCase()] !== undefined);
  if (!looksRussian) return text;
  return text.replace(/[a-zа-яёіїєґ'’]+/gi, (w) => (w.length === 1 && !RUSSIAN_ONLY.test(text) ? w : convertWord(w))) as T;
}
